"""Критерии качества: ISO/IEC/IEEE 29148:2018 (5.2.5, 5.2.6) и IEEE Std 830-1998 (4.3)."""
from typing import Dict, NamedTuple


class Criterion(NamedTuple):
    name: str
    source: str
    description: str


# Свойства отдельного требования
REQUIREMENT: Dict[str, Criterion] = {
    "necessary": Criterion("Необходимость", "29148 §5.2.5",
                           "Без требования теряется нужная возможность; нет дублей и лишнего."),
    "implementation_free": Criterion("Уместность уровня (без проектных решений)", "29148 §5.2.5",
                                     "Говорит «что», а не «как»; не навязывает лишних решений реализации."),
    "unambiguous": Criterion("Однозначность", "29148 §5.2.5; IEEE 830 §4.3.2",
                             "Допускает только одно толкование; термины, единицы, границы определены."),
    "complete": Criterion("Полнота", "29148 §5.2.5; IEEE 830 §4.3.3",
                          "Описаны все условия, ошибки, граничные и альтернативные случаи; нет TBD."),
    "singular": Criterion("Единичность (атомарность)", "29148 §5.2.5",
                          "Одно требование — одна возможность или ограничение."),
    "feasible": Criterion("Выполнимость", "29148 §5.2.5",
                          "Реализуемо в заданных ограничениях."),
    "verifiable": Criterion("Проверяемость", "29148 §5.2.5; IEEE 830 §4.3.6",
                            "Есть объективный критерий проверки: измеримые величины, ожидаемый результат."),
    "correct": Criterion("Корректность", "29148 §5.2.5; IEEE 830 §4.3.1",
                         "Точно отражает потребность; не противоречит цели и фактам предметной области."),
    "conforming": Criterion("Соответствие шаблону", "29148 §5.2.5",
                            "Оформлено по принятому шаблону/стилю: ID, обязательные поля заполнены."),
}

# Свойства набора требований (спецификации)
SET: Dict[str, Criterion] = {
    "set_complete": Criterion("Полнота набора", "29148 §5.2.6; IEEE 830 §4.3.3",
                              "Покрыты все функции, данные, интерфейсы, ошибки, NFR; нет пустых разделов."),
    "set_consistent": Criterion("Непротиворечивость", "29148 §5.2.6; IEEE 830 §4.3.4",
                                "Требования, критерии приёмки и спецификации не противоречат друг другу; термины едины."),
    "set_feasible": Criterion("Выполнимость набора", "29148 §5.2.6",
                              "Весь набор реализуем вместе в ограничениях проекта."),
    "set_comprehensible": Criterion("Понятность", "29148 §5.2.6",
                                    "Ясно, что ожидается от системы и как требования связаны."),
    "set_validatable": Criterion("Возможность валидации", "29148 §5.2.6",
                                 "Можно доказать, что набор удовлетворяет потребность: есть критерии приёмки."),
    "ranked": Criterion("Ранжированность", "IEEE 830 §4.3.5",
                        "Указаны важность и/или стабильность требований."),
    "modifiable": Criterion("Модифицируемость", "IEEE 830 §4.3.7",
                            "Структура, версия, нет избыточности, которая мешает изменениям."),
    "traceable": Criterion("Трассируемость", "IEEE 830 §4.3.8",
                           "Связи с источником и между документами (часть A ↔ API, требования ↔ тесты) ясны."),
}

ALL: Dict[str, Criterion] = {**REQUIREMENT, **SET}


def as_prompt(criteria: Dict[str, Criterion]) -> str:
    """Список критериев для вставки в промпт."""
    return "\n".join(f"- {code} — {c.name} ({c.source}): {c.description}" for code, c in criteria.items())
